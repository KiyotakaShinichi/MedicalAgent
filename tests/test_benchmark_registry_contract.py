"""The consolidated registry must only demand evidence Ship can actually produce.

Ship reached step 77 and blocked on `critical_status: missing`. Three critical
benchmarks lived under the gitignored `Data/mle_monitoring/`, and no Ship step
generated any of them - the registry required artifacts the pipeline had no way
to create. They are not the same problem, and they do not get the same fix:

* **mle_readiness** is real release evidence. `docs/ci_cd.md` lists "MLE
  readiness hard gates must pass" and names the artifact; ci.yml and
  run_quality_gate.py already run the generator. It stays critical, and Ship now
  runs it.

* **current_vs_realism_candidate** pointed at a path the service itself calls
  LEGACY. The canonical `realism_candidate_ab_gate` spec already carries the
  same evidence, from the tracked output the release gate references, with an
  identical metric set. The critical spec was a stale duplicate and is gone.

* **synthetic_realism_candidate** cannot be generated by Ship at any price: its
  generator rewrites the tracked synthetic dataset that the tracked model
  metrics, lineage, leakage audit and locked holdout are all derived from.
  Re-tiered to supporting, so its absence stays visible without blocking a
  release for a generator that must not run.

None of this makes benchmark content green. Genuine failing and unideal results
are asserted below to be exactly as they were.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.services.benchmark_registry import _load_benchmark_specs  # noqa: E402
from scripts.ship_steps import all_steps  # noqa: E402

SPEC_PATH = ROOT / "config" / "benchmark_registry_specs.json"
RELEASE_CONFIG = ROOT / "config" / "release_gate_thresholds.yaml"

MLE_GENERATOR = "scripts/run_mle_checks.py"
REGISTRY_GENERATOR = "scripts/generate_benchmark_report.py"
UNSAFE_GENERATOR = "scripts/generate_realism_calibrated_dataset.py"


def _specs_by_id() -> dict[str, dict]:
    return {spec["id"]: spec for spec in _load_benchmark_specs()}


def _step_commands() -> list[str]:
    return [" ".join(step.command) for step in all_steps()]


def _index_of(fragment: str) -> int | None:
    return next((i for i, c in enumerate(_step_commands()) if fragment in c), None)


# --- 1-3: MLE readiness is generated, critical, and not suppressed ------------


def test_ship_generates_mle_readiness_before_the_registry() -> None:
    """The registry cannot report on evidence that was never produced."""
    generated_at = _index_of(MLE_GENERATOR)
    registry_at = _index_of(REGISTRY_GENERATOR)

    assert generated_at is not None, "Ship never runs the MLE readiness generator"
    assert registry_at is not None, "Ship never builds the consolidated registry"
    assert generated_at < registry_at, (
        f"MLE readiness runs at step {generated_at} but the registry is built at "
        f"{registry_at}; the artifact would still be missing"
    )


def test_mle_readiness_remains_critical() -> None:
    """It is documented release evidence, so it keeps blocking."""
    assert _specs_by_id()["mle_readiness"]["tier"] == "critical"


def test_the_mle_readiness_step_cannot_swallow_its_own_failure() -> None:
    """An unideal or failing readiness result must still fail the step.

    ship.py runs every step with `check=True`; this pins that the readiness
    step was not given some softening the others do not have.
    """
    step = next(s for s in all_steps() if MLE_GENERATOR in " ".join(s.command))
    assert getattr(step, "allow_failure", False) is False
    assert getattr(step, "continue_on_error", False) is False
    assert "||" not in " ".join(step.command), "the command swallows a non-zero exit"


def test_ship_generates_the_canonical_readiness_artifact() -> None:
    """No `--output-path` override: the registry reads the default location."""
    step = next(s for s in all_steps() if MLE_GENERATOR in " ".join(s.command))
    assert "--output-path" not in step.command, (
        "redirecting the output would leave the registry's path unwritten, which "
        "is exactly what ci.yml does and why Ship still saw it missing"
    )

    from backend.services.mle_readiness import DEFAULT_OUTPUT_PATH

    assert _specs_by_id()["mle_readiness"]["path"] == DEFAULT_OUTPUT_PATH


# --- 4-6: the legacy duplicate is gone, the canonical one is untouched --------


def test_the_legacy_realism_spec_is_absent() -> None:
    assert "current_vs_realism_candidate" not in _specs_by_id(), (
        "the stale legacy duplicate is back; it points at an output path the "
        "service itself marks LEGACY"
    )


def test_the_canonical_realism_spec_survives_unchanged() -> None:
    canonical = _specs_by_id()["realism_candidate_ab_gate"]
    assert canonical["tier"] == "supporting"
    assert canonical["path"] == "Data/evals/models/latest_realism_candidate_ab_gate.json"


def test_the_canonical_spec_carries_the_metrics_the_duplicate_did() -> None:
    """Which is what made the removed spec a duplicate rather than a loss."""
    canonical = _specs_by_id()["realism_candidate_ab_gate"]
    for metric in (
        "status",
        "decision",
        "candidate_use",
        "production_replacement_allowed",
        "classification_auroc_delta",
        "regression_mae_delta",
    ):
        assert metric in canonical["metrics"], f"{metric} is no longer reported"


def test_no_consumer_still_reads_the_removed_registry_id() -> None:
    """Removing a spec must not silently retire behaviour keyed to its id.

    `_next_actions` looked the old id up with `.get(..., {})`, so deleting the
    spec would have quietly stopped a promotion-language recommendation from
    ever firing again. It now reads the canonical row.
    """
    registry_source = (ROOT / "backend/services/benchmark_registry.py").read_text(encoding="utf-8")
    assert 'by_id.get("current_vs_realism_candidate"' not in registry_source

    coverage_source = (ROOT / "backend/services/failure_mode_registry.py").read_text(
        encoding="utf-8"
    )
    assert '"current_vs_realism_candidate"' not in coverage_source, (
        "a risk entry still claims coverage by a benchmark the registry no longer has"
    )


# --- 7-8: the unsafe benchmark is demoted, never scheduled -------------------


def test_synthetic_realism_candidate_is_supporting() -> None:
    assert _specs_by_id()["synthetic_realism_candidate"]["tier"] == "supporting"


def test_synthetic_realism_candidate_is_still_registered() -> None:
    """Demoted, not hidden: its missing or stale state stays visible."""
    spec = _specs_by_id()["synthetic_realism_candidate"]
    assert spec["path"] == "Data/mle_monitoring/synthetic_realism_candidate_report.json"
    assert spec["metrics"], "the benchmark stopped reporting anything"


def test_ship_never_regenerates_the_synthetic_dataset() -> None:
    """Its generator rewrites tracked data that frozen evidence derives from.

    `Data/complete_synthetic_breast_journeys_realism_v2` holds tracked dataset
    files, and the tracked model metrics, lineage, leakage audit and locked
    holdout manifest are all computed from them. Running this in Ship would
    rewrite the inputs underneath that evidence on every release.
    """
    assert _index_of(UNSAFE_GENERATOR) is None, (
        "Ship now regenerates the realism-calibrated dataset; frozen evidence "
        "would be rebuilt underneath itself"
    )
    assert _index_of("generate_complete_synthetic") is None


# --- 9-12: nothing about content, thresholds or honesty moved ----------------


def test_no_release_threshold_or_required_policy_changed() -> None:
    """The registry repair must not touch the release gate at all."""
    import subprocess

    diff = subprocess.run(
        ["git", "diff", "origin/main", "--", "config/release_gate_thresholds.yaml"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    assert not diff.stdout.strip(), "release_gate_thresholds.yaml was modified"


def test_the_release_gate_still_treats_the_realism_gate_as_optional() -> None:
    config = yaml.safe_load(RELEASE_CONFIG.read_text(encoding="utf-8"))
    found = []

    def walk(node):
        if isinstance(node, dict):
            if node.get("path") == "Data/evals/models/latest_realism_candidate_ab_gate.json":
                found.append(node)
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    walk(config)
    assert found, "the canonical realism gate left the release configuration"
    assert found[0]["required"] is False


def test_genuine_negative_results_are_untouched() -> None:
    """A failing benchmark stays failing; this task repairs contracts, not content."""
    from backend.services.benchmark_registry import _build_row

    specs = _specs_by_id()
    row = _build_row(specs["adversarial_safety_regression"], 24 * 60 * 60)
    assert row["tier"] == "supporting"
    assert row["source_status"] == "failed", (
        f"an honest failed result now reads {row['source_status']!r}"
    )


def test_no_benchmark_status_was_added_to_an_accepted_set() -> None:
    """Nothing was made green by widening what counts as acceptable."""
    source = (ROOT / "backend/services/benchmark_registry.py").read_text(encoding="utf-8")
    for bad in ("failed", "unideal", "missing"):
        assert f'"{bad}", "strong"' not in source
    assert '{"strong", "passed", "robust", "stable"}' in source, (
        "the strong-status set changed; statuses may have been reclassified"
    )


def test_the_spec_file_is_still_valid_json_with_every_tier_known() -> None:
    payload = json.loads(SPEC_PATH.read_text(encoding="utf-8"))
    specs = payload if isinstance(payload, list) else (
        payload.get("benchmarks") or payload.get("specs")
    )
    assert specs, "the spec file lost its benchmarks"
    known = {"critical", "supporting", "optional", "informational"}
    for spec in specs:
        assert spec["tier"] in known, f"{spec['id']} has unknown tier {spec['tier']!r}"
        assert spec.get("path"), f"{spec['id']} names no artifact"


@pytest.mark.parametrize("benchmark_id", ["mle_readiness", "synthetic_realism_candidate"])
def test_the_remaining_mle_monitoring_benchmarks_keep_their_paths(benchmark_id: str) -> None:
    """Re-tiering must not quietly move an artifact somewhere else."""
    assert _specs_by_id()[benchmark_id]["path"].startswith("Data/mle_monitoring/")
